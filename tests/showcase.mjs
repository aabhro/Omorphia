// Loads the real showcase page (index.html + dist + showcase.js) and checks that every demo renders and nothing throws.
import { JSDOM, VirtualConsole } from 'jsdom';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const errs = []; const vc = new VirtualConsole(); vc.on('jsdomError', (e) => { if (!/stylesheet|fonts\.g|Could not load link/i.test(e.message)) errs.push(e.message); }); vc.on('error', (e) => errs.push(String(e))); vc.on('warn', (e) => errs.push(String(e)));
const dom = await JSDOM.fromFile('index.html', { runScripts: 'dangerously', resources: 'usable', pretendToBeVisual: true, virtualConsole: vc, beforeParse(w) { w.Element.prototype.scrollIntoView = () => {}; w.fetch = async () => ({ ok: false }); w.navigator.clipboard = { writeText: async () => {} }; } });
await new Promise((r) => dom.window.addEventListener('load', r)); await new Promise((r) => setTimeout(r, 300));
const d = dom.window.document;
const demos = [...d.querySelectorAll('.demo')];
assert.ok(demos.length >= 25, `demos: ${demos.length}`);
assert.equal(d.querySelectorAll('.demo template').length, 0, 'every demo template was rendered');
assert.ok([...d.querySelectorAll('.demo-code pre')].every((p) => p.textContent.trim().length > 10), 'code panels populated');
for (const s of ['type', 'buttons', 'inputs', 'navigation', 'feedback', 'containers', 'advanced', 'effects']) assert.ok(d.getElementById(s), s);
const sourceHtml = readFileSync('index.html', 'utf8');
assert.doesNotMatch(sourceHtml, /<(?:button|input|textarea|select|option|details)\b/i, 'showcase authors custom controls, not raw native widgets');
for (const name of ['ui-input', 'ui-textarea', 'ui-checkbox', 'ui-radio', 'ui-switch', 'ui-range', 'ui-option', 'ui-select', 'ui-date-picker', 'ui-time-picker', 'ui-menu-item', 'ui-drawer', 'ui-accordion', 'ui-accordion-item']) {
  assert.ok(dom.window.customElements.get(name), name + ' is registered');
}
assert.ok(d.querySelector('#i-name')?.matches('ui-input'), 'text fields use the custom input');
assert.ok(d.querySelector('#i-t')?.matches('ui-textarea'), 'notes use the custom textarea');
assert.ok(d.querySelector('#i-s')?.matches('ui-select'), 'selects use the custom select');
assert.ok(d.querySelectorAll('ui-date-picker').length >= 1, 'date picker demo renders');
assert.ok(d.querySelectorAll('ui-time-picker').length >= 1, 'time picker demo renders');
assert.ok(d.querySelector('#settings-drawer')?.matches('ui-drawer'), 'drawer demo renders');
assert.ok(d.querySelectorAll('ui-accordion ui-accordion-item').length >= 2, 'accordion demo renders');
const codePanels = [...d.querySelectorAll('ui-accordion.demo-code')];
assert.ok(codePanels.length >= 25 && codePanels.every((panel) => panel.firstElementChild?.matches('ui-accordion-item')), 'example code disclosures use the accordion component');
assert.equal(d.querySelector('#settings-drawer').hidden, true, 'drawer starts closed');
const deployChoice = d.querySelector('#choice-deploys');
const weeklyChoice = d.querySelector('#choice-weekly');
const starterChoice = d.querySelector('#choice-starter');
const teamChoice = d.querySelector('#choice-team');
assert.ok(deployChoice && weeklyChoice && starterChoice && teamChoice, 'the choice demo renders every option');
deployChoice.control.click();
assert.equal(deployChoice.checked, false, 'the checked deploy checkbox toggles off');
weeklyChoice.text.click();
assert.equal(weeklyChoice.checked, true, 'the weekly summary label toggles its checkbox');
teamChoice.control.click();
assert.equal(teamChoice.checked, true, 'the Team radio selects');
assert.equal(starterChoice.checked, false, 'the Starter radio deselects');
const datePicker = d.querySelector('#date-demo');
assert.equal(datePicker.value, '2026-11-20');
assert.equal(datePicker.days.children.length, 42, 'calendar renders a six-week grid');
datePicker.show();
assert.equal(datePicker.open, true, 'the showcase date trigger opens its calendar');
assert.equal(dom.window.getComputedStyle(datePicker.popoverElement.panel).position, 'fixed', 'floating picker panel is positioned without relying on native popover support');
assert.equal(dom.window.getComputedStyle(datePicker.popoverElement.panel).pointerEvents, 'auto', 'floating picker panel accepts pointer interaction inside its non-interactive layer');
const floatingLayer = d.querySelector('[data-ui-floating-layer]');
assert.ok(floatingLayer, 'floating panels use the shared viewport layer');
assert.equal(datePicker.popoverElement.panel.parentElement, floatingLayer, 'date calendar escapes the clipped preview frame');
datePicker.days.querySelector('[data-date="2026-11-21"]').click();
assert.equal(datePicker.value, '2026-11-21', 'the showcase date picker changes its value');
assert.equal(d.getElementById('date-demo-output').textContent, '2026-11-21', 'the showcase readout follows the selected date');
assert.equal(datePicker.open, false, 'selecting a date closes the calendar');
datePicker.trigger.click();
assert.equal(datePicker.open, true, 'the date picker trigger also opens the calendar');
datePicker.hide();
assert.equal(datePicker.open, false, 'the date picker host can close its own calendar');
const timePicker = d.querySelector('#time-demo');
assert.equal(timePicker.value, '14:30');
assert.equal(timePicker.input.value, '2:30 PM');
assert.equal(timePicker.input.getAttribute('aria-label'), 'Basic time picker');
timePicker.input.value = '3:45 PM';
timePicker.input.dispatchEvent(new dom.window.Event('input', { bubbles: true }));
timePicker.input.dispatchEvent(new dom.window.Event('change', { bubbles: true }));
assert.equal(timePicker.value, '15:45', 'the showcase time field accepts typed values');
assert.equal(timePicker.input.value, '3:45 PM', 'the showcase preserves typed display format');
timePicker.value = '14:30';
timePicker.show();
assert.equal(timePicker.open, true, 'the showcase time trigger opens its panel');
assert.equal(timePicker.popoverElement.panel.parentElement, floatingLayer, 'time panel escapes the clipped preview frame');
timePicker.minuteList.querySelector('[data-minute="35"]').click();
assert.equal(timePicker.value, '14:35', 'the showcase time picker changes its value');
assert.equal(d.getElementById('time-demo-output').textContent, '2:35 PM', 'the showcase readout follows the selected time');
timePicker.hide();
assert.equal(timePicker.open, false, 'the showcase time panel closes on request');
timePicker.trigger.click();
assert.equal(timePicker.open, true, 'the time picker trigger opens the panel');
timePicker.toggle();
assert.equal(timePicker.open, false, 'the time picker host toggles its own panel closed');
const outerPopover = d.querySelector('#nested-popover-outer');
const innerPopover = d.querySelector('#nested-popover-inner');
outerPopover.show();
innerPopover.show();
assert.equal(outerPopover.open, true);
assert.equal(innerPopover.open, true);
assert.equal(innerPopover.panel.parentElement, floatingLayer, 'nested popovers share the viewport layer');
assert.ok(Number(innerPopover.panel.style.zIndex) > Number(outerPopover.panel.style.zIndex), 'the nested surface stacks above its parent');
innerPopover.panel.dispatchEvent(new dom.window.Event('pointerdown', { bubbles: true }));
assert.equal(outerPopover.open, true, 'interacting with a child panel does not dismiss its parent');
assert.equal(innerPopover.open, true, 'interacting inside the child panel leaves it open');
innerPopover.hide();
outerPopover.hide();
assert.ok(d.querySelectorAll('ui-menu-item').length >= 3, 'dropdown examples use custom menu items');
const missing = [...d.querySelectorAll('ui-icon')].filter((i) => !i.querySelector('svg')).map((i) => i.getAttribute('name'));
assert.deepEqual(missing, [], 'all icons render from the bundle: ' + missing);
assert.ok(d.querySelector('#search-local').data.length > 10); assert.ok(d.getElementById('actions-menu').panel);
assert.ok(d.querySelector('[data-fx-preset="balanced"]'), 'live configuration presets render');
assert.ok(d.getElementById('fx-copy'), 'live configuration copy action renders');
assert.equal(d.querySelectorAll('#overlay-effects .overlay-effect-preview').length, 1, 'one page fade preview renders');
assert.ok(d.querySelector('#overlay-effects .ui-page-fade'), 'the preview overlays the full sample page');
assert.equal(d.querySelectorAll('.main > .ui-page-fade').length, 1, 'one fade is attached to the main content, not the sidebar');
const showcaseStyles = readFileSync('showcase/showcase.css', 'utf8');
const popoverStyleStart = showcaseStyles.indexOf('.ui-popover-panel {');
const popoverStyleEnd = showcaseStyles.indexOf('}', popoverStyleStart);
assert.ok(popoverStyleStart >= 0, 'showcase popover layout rule exists');
assert.doesNotMatch(showcaseStyles.slice(popoverStyleStart, popoverStyleEnd), /background\s*:|color\s*:/, 'showcase layered panels inherit the active theme');
assert.ok((d.querySelector('link[rel="icon"]')?.getAttribute('href') || '').endsWith('favicon.svg'));
assert.match(d.title, /Omorphia/);
const packageVersion = JSON.parse(readFileSync('package.json', 'utf8')).version;
assert.ok(d.body.innerHTML.includes(`@v${packageVersion}/dist/omorphia.min.js`), 'showcase CDN example matches the package version');
assert.ok(d.getElementById('fx-css-output')?.textContent.includes('--ui-edge-tl-alpha'), 'live configuration emits CSS');
const showcaseCss = readFileSync('showcase/showcase.css', 'utf8');
for (const selector of ['.demo-code pre {', '.fx-code {']) {
  const start = showcaseCss.indexOf(selector);
  const rule = showcaseCss.slice(start, showcaseCss.indexOf('}', start));
  assert.ok(start >= 0 && rule.includes('background: var(--ui-bg-inset)'), selector + ' follows the active theme');
}
const palette = d.querySelector('ui-command-palette');
assert.ok(palette, 'command palette host exists');
assert.equal(palette.dialog.parentElement, d.body, 'command dialog lives outside its display:none host');
const notes = d.getElementById('i-t');
assert.ok(notes, 'Notes textarea is present in the demo');
assert.equal(dom.window.getComputedStyle(notes.frame).borderRadius, '0px', 'Notes textarea frame has square corners');
const displaySwitch = d.querySelector('ui-popover ui-switch');
assert.ok(displaySwitch, 'popover contains a live switch');
assert.equal(dom.window.getComputedStyle(displaySwitch.control).width, '38px', 'switch reserves the full track width');
assert.equal(dom.window.getComputedStyle(displaySwitch).width, '100%', 'popover switch uses the available panel width');
const initialSwitchState = displaySwitch.checked;
displaySwitch.querySelector('.ui-choice-label').click();
assert.equal(displaySwitch.checked, !initialSwitchState, 'popover switch label remains independently clickable');
let targetHandlerReached = false;
notes.addEventListener('keydown', (event) => { targetHandlerReached = true; event.stopPropagation(); });
notes.focus();
const shortcut = new dom.window.KeyboardEvent('keydown', { key: 'k', code: 'KeyK', ctrlKey: true, shiftKey: true, bubbles: true, cancelable: true });
notes.dispatchEvent(shortcut);
assert.ok(palette.isOpen, 'Ctrl+Shift+K opens the command palette from the Notes demo field');
assert.ok(shortcut.defaultPrevented, 'Ctrl+K is prevented from triggering browser UI');
assert.equal(targetHandlerReached, false, 'the capture shortcut is handled before focused controls');
for (const field of d.querySelectorAll('input, textarea, select')) assert.ok(field.id || field.name, `internal form control has an id or name: ${field.outerHTML}`);
for (const control of d.querySelectorAll('ui-input, ui-textarea, ui-select, ui-date-picker, ui-time-picker, ui-range, ui-checkbox, ui-radio, ui-switch')) assert.ok(control.id || control.getAttribute('name') || control.getAttribute('label'), `custom control is identifiable: ${control.outerHTML.slice(0, 180)}`);
palette.close();
let outsideClicks = 0;
const outside = d.createElement('button');
outside.type = 'button';
outside.textContent = 'Interaction check';
outside.addEventListener('click', () => outsideClicks++);
d.body.append(outside);
outside.click();
assert.equal(outsideClicks, 1, 'page controls remain interactive after closing the palette');
outside.remove();
const openTrigger = d.querySelector('.topbar ui-button[icon="search"]');
assert.ok(openTrigger, 'showcase command palette trigger exists');
openTrigger.click();
assert.ok(palette.isOpen, 'the visible showcase button opens the command palette');
assert.equal(palette.dialog.parentElement, d.body, 'button-opened dialog is portalled to the document body');
palette.close();
palette.open(); assert.ok(d.querySelectorAll('.ui-command .ui-option').length >= 11, 'palette lists commands');
assert.deepEqual(errs, [], 'console clean');
console.log(`showcase OK — ${demos.length} demos, ${d.querySelectorAll('ui-icon svg').length} icons rendered`);
process.exit(0);
