// Loads the real showcase page (index.html + dist + showcase.js) and checks that every demo renders and nothing throws.
import { JSDOM, VirtualConsole } from 'jsdom';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const errs = []; const vc = new VirtualConsole(); vc.on('jsdomError', (e) => { if (!/stylesheet|fonts\.g|Could not load link/i.test(e.message)) errs.push(e.message); }); vc.on('error', (e) => errs.push(String(e))); vc.on('warn', (e) => errs.push(String(e)));
const dom = await JSDOM.fromFile('index.html', { runScripts: 'dangerously', resources: 'usable', pretendToBeVisual: true, virtualConsole: vc, beforeParse(w) { w.Element.prototype.scrollIntoView = () => {}; w.fetch = async () => ({ ok: false }); w.navigator.clipboard = { writeText: async () => {} }; } });
await new Promise((r) => dom.window.addEventListener('load', r)); await new Promise((r) => setTimeout(r, 300));
const d = dom.window.document;
const demos = [...d.querySelectorAll('.demo')];
assert.ok(demos.length >= 25, `demos: ${demos.length}`);
assert.equal(d.querySelectorAll('.demo template').length, 0, 'every demo template was rendered');
assert.ok([...d.querySelectorAll('.demo-code pre')].every((p) => p.textContent.trim().length > 10), 'code panels populated');
for (const s of ['type', 'buttons', 'inputs', 'navigation', 'feedback', 'containers', 'advanced', 'effects']) assert.ok(d.getElementById(s), s);
const missing = [...d.querySelectorAll('ui-icon')].filter((i) => !i.querySelector('svg')).map((i) => i.getAttribute('name'));
assert.deepEqual(missing, [], 'all icons render from the bundle: ' + missing);
assert.ok(d.querySelector('#search-local').data.length > 10); assert.ok(d.getElementById('actions-menu').panel);
assert.ok(d.querySelector('[data-fx-preset="balanced"]'), 'live configuration presets render');
assert.ok(d.getElementById('fx-copy'), 'live configuration copy action renders');
assert.ok((d.querySelector('link[rel="icon"]')?.getAttribute('href') || '').endsWith('favicon.svg'));
assert.match(d.title, /Omorphia/);
const packageVersion = JSON.parse(readFileSync('package.json', 'utf8')).version;
assert.ok(d.body.innerHTML.includes(`@v${packageVersion}/dist/omorphia.min.js`), 'showcase CDN example matches the package version');
assert.ok(d.getElementById('fx-css-output')?.textContent.includes('--ui-edge-tl-alpha'), 'live configuration emits CSS');
const palette = d.querySelector('ui-command-palette');
assert.ok(palette, 'command palette host exists');
assert.equal(palette.dialog.parentElement, d.body, 'command dialog lives outside its display:none host');
const notes = d.getElementById('i-t');
assert.ok(notes, 'Notes textarea is present in the demo');
let targetHandlerReached = false;
notes.addEventListener('keydown', (event) => { targetHandlerReached = true; event.stopPropagation(); });
notes.focus();
const shortcut = new dom.window.KeyboardEvent('keydown', { key: 'k', code: 'KeyK', ctrlKey: true, shiftKey: true, bubbles: true, cancelable: true });
notes.dispatchEvent(shortcut);
assert.ok(palette.isOpen, 'Ctrl+Shift+K opens the command palette from the Notes demo field');
assert.ok(shortcut.defaultPrevented, 'Ctrl+K is prevented from triggering browser UI');
assert.equal(targetHandlerReached, false, 'the capture shortcut is handled before focused controls');
for (const field of d.querySelectorAll('input, textarea, select')) assert.ok(field.id || field.name, `field has an id or name: ${field.outerHTML}`);
palette.close();
let outsideClicks = 0;
const outside = d.createElement('button');
outside.type = 'button';
outside.textContent = 'Interaction check';
outside.addEventListener('click', () => outsideClicks++);
d.body.append(outside);
outside.click();
assert.equal(outsideClicks, 1, 'page controls remain interactive after closing the palette');
outside.remove();
const openTrigger = d.querySelector('.topbar ui-button[icon="search"]');
assert.ok(openTrigger, 'showcase command palette trigger exists');
openTrigger.click();
assert.ok(palette.isOpen, 'the visible showcase button opens the command palette');
assert.equal(palette.dialog.parentElement, d.body, 'button-opened dialog is portalled to the document body');
palette.close();
palette.open(); assert.ok(d.querySelectorAll('.ui-command .ui-option').length >= 11, 'palette lists commands');
assert.deepEqual(errs, [], 'console clean');
console.log(`showcase OK — ${demos.length} demos, ${d.querySelectorAll('ui-icon svg').length} icons rendered`);
process.exit(0);
